//! Renders a pod's firewall as an nftables ruleset. The ruleset lives in
//! its own `inet kirisame` table inside the pod's network namespace, so it
//! never touches the host's rules.

use crate::errors::{Error, Result};
use crate::project::{Action, Addressing, Peer, Pod, Project, Proto, Rule};
use ipnet::IpNet;
use std::fmt::Write;

pub const TABLE: &str = "kirisame";

/// Looks up the current addresses of a pod (static or leased).
pub trait AddressBook {
    fn pod_addresses(&self, pod: &str) -> Vec<IpNet>;
}

impl<F: Fn(&str) -> Vec<IpNet>> AddressBook for F {
    fn pod_addresses(&self, pod: &str) -> Vec<IpNet> {
        self(pod)
    }
}

/// Builds the ruleset for `pod`, or None when the pod has no firewall.
/// The result replaces the table atomically when fed to `nft -f`.
pub fn render(project: &Project, pod: &Pod, book: &dyn AddressBook) -> Result<Option<String>> {
    let Some(fw) = &pod.firewall else {
        return Ok(None);
    };
    let dhcp = pod
        .attachments
        .iter()
        .any(|a| a.addressing == Addressing::Dhcp);
    let mut input = fw.input.clone();
    let mut output = fw.output.clone();

    // `ports:` open to everyone, `expose:` to the project's other pods.
    let others: Vec<Peer> = project
        .pods
        .keys()
        .filter(|p| **p != pod.name)
        .map(|p| Peer::Pod(p.clone()))
        .collect();
    for svc in project.services_in_pod(&pod.name) {
        for (proto, range) in &svc.ports {
            input.push(port_rule(*proto, *range, vec![], &svc.name, "ports"));
        }
        if !others.is_empty() {
            for (proto, range) in &svc.expose {
                input.push(port_rule(
                    *proto,
                    *range,
                    others.clone(),
                    &svc.name,
                    "expose",
                ));
            }
        }
    }
    // Output rules toward a closed policy still need answers to come back,
    // which conntrack handles; nothing else is implied.

    let mut out = String::new();
    let w = &mut out;
    let _ = writeln!(
        w,
        "# Generated by kirisame for pod {} in project {}. Do not edit.",
        pod.name, project.name
    );
    let _ = writeln!(w, "table inet {TABLE}");
    let _ = writeln!(w, "delete table inet {TABLE}");
    let _ = writeln!(w, "table inet {TABLE} {{");

    let _ = writeln!(w, "  chain input {{");
    let _ = writeln!(
        w,
        "    type filter hook input priority filter; policy {};",
        policy(fw.input_policy)
    );
    let _ = writeln!(w, "    iif \"lo\" accept comment \"intra-pod traffic\"");
    let _ = writeln!(w, "    ct state established,related accept");
    let _ = writeln!(w, "    ct state invalid drop");
    let _ = writeln!(
        w,
        "    icmpv6 type {{ destination-unreachable, packet-too-big, time-exceeded, parameter-problem, nd-router-advert, nd-neighbor-solicit, nd-neighbor-advert }} accept"
    );
    let _ = writeln!(
        w,
        "    icmp type {{ destination-unreachable, time-exceeded, parameter-problem }} accept"
    );
    if fw.allow_ping {
        let _ = writeln!(w, "    icmp type echo-request accept");
        let _ = writeln!(w, "    icmpv6 type echo-request accept");
    }
    if dhcp {
        let _ = writeln!(w, "    udp sport 67 udp dport 68 accept comment \"dhcp\"");
    }
    for (i, r) in input.iter().enumerate() {
        for line in rule_lines(project, pod, r, true, book)
            .map_err(|e| Error::Firewall(format!("pod {} input[{i}]: {e}", pod.name)))?
        {
            let _ = writeln!(w, "    {line}");
        }
    }
    if fw.log_dropped && fw.input_policy != Action::Accept {
        let _ = writeln!(
            w,
            "    limit rate 10/second log prefix \"{}\"",
            log_prefix(pod, "in")
        );
    }
    if fw.input_policy == Action::Reject {
        let _ = writeln!(w, "    reject with icmpx admin-prohibited");
    }
    let _ = writeln!(w, "  }}");

    let _ = writeln!(w, "  chain output {{");
    let _ = writeln!(
        w,
        "    type filter hook output priority filter; policy {};",
        policy(fw.output_policy)
    );
    let _ = writeln!(w, "    oif \"lo\" accept comment \"intra-pod traffic\"");
    let _ = writeln!(w, "    ct state established,related accept");
    let _ = writeln!(
        w,
        "    icmpv6 type {{ nd-router-solicit, nd-neighbor-solicit, nd-neighbor-advert, packet-too-big, destination-unreachable, time-exceeded, parameter-problem }} accept"
    );
    if dhcp {
        let _ = writeln!(w, "    udp sport 68 udp dport 67 accept comment \"dhcp\"");
    }
    for (i, r) in output.iter_mut().enumerate() {
        for line in rule_lines(project, pod, r, false, book)
            .map_err(|e| Error::Firewall(format!("pod {} output[{i}]: {e}", pod.name)))?
        {
            let _ = writeln!(w, "    {line}");
        }
    }
    if fw.log_dropped && fw.output_policy != Action::Accept {
        let _ = writeln!(
            w,
            "    limit rate 10/second log prefix \"{}\"",
            log_prefix(pod, "out")
        );
    }
    if fw.output_policy == Action::Reject {
        let _ = writeln!(w, "    reject with icmpx admin-prohibited");
    }
    let _ = writeln!(w, "  }}");
    let _ = writeln!(w, "}}");
    Ok(Some(out))
}

/// The base chains take `drop` for both drop and reject; reject is done by
/// a final rule so the policy itself stays valid nft.
fn policy(a: Action) -> &'static str {
    match a {
        Action::Accept => "accept",
        Action::Drop | Action::Reject => "drop",
    }
}

fn log_prefix(pod: &Pod, dir: &str) -> String {
    // nft log prefixes are capped at 127 bytes; keep them short and useful.
    let mut name = pod.name.clone();
    name.truncate(40);
    format!("kirisame {name} {dir} drop: ")
}

fn port_rule(
    proto: Proto,
    range: crate::project::PortRange,
    peers: Vec<Peer>,
    svc: &str,
    why: &str,
) -> Rule {
    Rule {
        action: Action::Accept,
        protocols: vec![proto],
        ports: vec![range],
        peers,
        interface: None,
        log: false,
        limit: None,
        comment: Some(format!("{why} of service {svc}")),
    }
}

/// Expands one rule into nft statements. A rule whose peers mix IPv4 and
/// IPv6 becomes two statements, one per family.
fn rule_lines(
    project: &Project,
    pod: &Pod,
    r: &Rule,
    input: bool,
    book: &dyn AddressBook,
) -> std::result::Result<Vec<String>, String> {
    let mut v4 = Vec::new();
    let mut v6 = Vec::new();
    for peer in &r.peers {
        let nets: Vec<IpNet> = match peer {
            Peer::Any => vec![],
            Peer::Cidr(n) => vec![*n],
            Peer::Pod(p) => host_routes(book.pod_addresses(p)),
            Peer::Service(s) => {
                let svc = project
                    .services
                    .get(s)
                    .ok_or_else(|| format!("unknown service {s}"))?;
                host_routes(book.pod_addresses(&svc.pod))
            }
            Peer::Network(n) => project
                .networks
                .get(n)
                .ok_or_else(|| format!("unknown network {n}"))?
                .subnets
                .iter()
                .map(|s| s.cidr)
                .collect(),
        };
        for n in nets {
            match n {
                IpNet::V4(_) => v4.push(n),
                IpNet::V6(_) => v6.push(n),
            }
        }
    }
    let has_peers = !r.peers.is_empty();
    let unresolved: Vec<&Peer> = r
        .peers
        .iter()
        .filter(|p| match p {
            Peer::Pod(name) => book.pod_addresses(name).is_empty(),
            Peer::Service(s) => project
                .services
                .get(s)
                .is_none_or(|svc| book.pod_addresses(&svc.pod).is_empty()),
            _ => false,
        })
        .collect();
    if !unresolved.is_empty() && r.action != Action::Accept {
        // Skipping a deny rule would let the peer through: refuse instead.
        return Err(format!(
            "{} has no address yet, so this {} rule cannot be applied; wait for its lease and run `kirisame firewall reload`",
            describe_peers(&unresolved),
            r.action.as_nft()
        ));
    }
    if has_peers && v4.is_empty() && v6.is_empty() {
        // An accept rule whose peers have no address yet matches nothing:
        // emit nothing rather than a rule that would match everyone.
        return Ok(vec![format!(
            "# skipped: no addresses known yet for {} in pod {}",
            describe_peers(&r.peers.iter().collect::<Vec<_>>()),
            pod.name
        )]);
    }

    let dir = if input { "saddr" } else { "daddr" };
    let mut families: Vec<(Option<&str>, Vec<IpNet>)> = Vec::new();
    if has_peers {
        if !v4.is_empty() {
            families.push((Some("ip"), v4));
        }
        if !v6.is_empty() {
            families.push((Some("ip6"), v6));
        }
    } else {
        families.push((None, vec![]));
    }

    let mut lines = Vec::new();
    for (family, nets) in families {
        let mut parts: Vec<String> = Vec::new();
        if let Some(i) = &r.interface {
            parts.push(format!(
                "{} \"{i}\"",
                if input { "iifname" } else { "oifname" }
            ));
        }
        if let Some(f) = family {
            parts.push(format!(
                "{f} {dir} {}",
                set(nets.iter().map(ToString::to_string))
            ));
        }
        let protos = &r.protocols;
        let ports = set(r.ports.iter().map(ToString::to_string));
        match (protos.as_slice(), r.ports.is_empty()) {
            ([], _) => {}
            ([Proto::Tcp], false) => parts.push(format!("tcp dport {ports}")),
            ([Proto::Udp], false) => parts.push(format!("udp dport {ports}")),
            (ps, false) => parts.push(format!(
                "meta l4proto {} th dport {ports}",
                set(ps.iter().map(|p| proto_name(*p).into()))
            )),
            ([p], true) => parts.push(format!("meta l4proto {}", proto_name(*p))),
            (ps, true) => parts.push(format!(
                "meta l4proto {}",
                set(ps.iter().map(|p| proto_name(*p).into()))
            )),
        }
        // Skip families that cannot match the protocol (icmp over ip6).
        if family == Some("ip6") && protos.iter().all(|p| *p == Proto::Icmp) && !protos.is_empty() {
            continue;
        }
        if family == Some("ip") && protos.iter().all(|p| *p == Proto::Icmpv6) && !protos.is_empty()
        {
            continue;
        }
        if let Some(l) = &r.limit {
            parts.push(format!("limit rate {l}"));
        }
        if r.log {
            parts.push(format!(
                "log prefix \"{}\"",
                log_prefix(pod, if input { "in" } else { "out" }).replace(" drop", "")
            ));
        }
        parts.push(match r.action {
            Action::Reject => "reject with icmpx admin-prohibited".into(),
            a => a.as_nft().into(),
        });
        if let Some(c) = &r.comment {
            parts.push(format!("comment \"{c}\""));
        }
        lines.push(parts.join(" "));
    }
    Ok(lines)
}

fn describe_peers(peers: &[&Peer]) -> String {
    peers
        .iter()
        .map(|p| match p {
            Peer::Any => "any".to_string(),
            Peer::Cidr(n) => n.to_string(),
            Peer::Pod(x) => format!("pod:{x}"),
            Peer::Service(x) => format!("service:{x}"),
            Peer::Network(x) => format!("network:{x}"),
        })
        .collect::<Vec<_>>()
        .join(", ")
}

fn proto_name(p: Proto) -> &'static str {
    match p {
        Proto::Tcp => "tcp",
        Proto::Udp => "udp",
        Proto::Icmp => "icmp",
        Proto::Icmpv6 => "ipv6-icmp",
    }
}

/// A pod's interface addresses carry the subnet prefix; as a firewall peer
/// we want the host itself, not its whole subnet.
fn host_routes(addrs: Vec<IpNet>) -> Vec<IpNet> {
    addrs.into_iter().map(|a| IpNet::from(a.addr())).collect()
}

fn set(items: impl Iterator<Item = String>) -> String {
    let v: Vec<String> = items.collect();
    if v.len() == 1 {
        v[0].clone()
    } else {
        format!("{{ {} }}", v.join(", "))
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::compose::{LoadOptions, load};

    fn project(yaml: &str) -> Project {
        let dir = tempfile::tempdir().unwrap();
        std::fs::write(dir.path().join("compose.yaml"), yaml).unwrap();
        let opts = LoadOptions {
            cwd: Some(dir.path().to_path_buf()),
            ..Default::default()
        };
        load(&opts).unwrap().project
    }

    const BASE: &str = r#"
name: demo
networks:
  lan:
    driver: macvlan
    driver_opts: { parent: eth9 }
    ipam:
      config: [{ subnet: 192.0.2.0/24, gateway: 192.0.2.1 }]
pods:
  web:
    networks: { lan: { ipv4_address: 192.0.2.10 } }
    firewall:
      log_dropped: true
      input:
        - { proto: tcp, ports: [80, 443] }
        - { proto: tcp, port: 9000, from: [pod:db, "2001:db8::/32"] }
        - { proto: [tcp, udp], port: "5000-5010", from: network:lan, action: drop, limit: 5/second }
      output:
        - { to: 198.51.100.0/24, action: reject }
  db:
    networks: { lan: { dhcp: true } }
services:
  nginx: { image: nginx, pod: web, ports: ["8080:8080"] }
  pg: { image: postgres, pod: db, expose: ["5432"] }
"#;

    #[test]
    fn renders_rules() {
        let p = project(BASE);
        let book = |pod: &str| -> Vec<IpNet> {
            match pod {
                "db" => vec!["192.0.2.50/24".parse().unwrap()],
                "web" => vec!["192.0.2.10/24".parse().unwrap()],
                _ => vec![],
            }
        };
        let rs = render(&p, &p.pods["web"], &book).unwrap().unwrap();
        assert!(rs.contains("policy drop;"), "{rs}");
        assert!(rs.contains("iif \"lo\" accept"));
        assert!(rs.contains("tcp dport { 80, 443 } accept"));
        assert!(
            rs.contains("ip saddr 192.0.2.50/32 tcp dport 9000 accept"),
            "{rs}"
        );
        assert!(
            rs.contains("ip6 saddr 2001:db8::/32 tcp dport 9000 accept"),
            "{rs}"
        );
        assert!(rs.contains("ip saddr 192.0.2.0/24 meta l4proto { tcp, udp } th dport 5000-5010 limit rate 5/second drop"), "{rs}");
        assert!(
            rs.contains("ip daddr 198.51.100.0/24 reject with icmpx admin-prohibited"),
            "{rs}"
        );
        assert!(
            rs.contains("tcp dport 8080 accept comment \"ports of service nginx\""),
            "{rs}"
        );
        assert!(rs.contains("log prefix \"kirisame web in drop: \""));
        assert!(!rs.contains("dhcp"));
        // The db pod has no firewall section, so nothing is rendered.
        assert!(render(&p, &p.pods["db"], &book).unwrap().is_none());
    }

    #[test]
    fn dhcp_and_expose() {
        let yaml = BASE.replace(
            "  db:\n    networks: { lan: { dhcp: true } }",
            "  db:\n    networks: { lan: { dhcp: true } }\n    firewall: {}",
        );
        let p = project(&yaml);
        let book = |pod: &str| -> Vec<IpNet> {
            if pod == "web" {
                vec!["192.0.2.10/24".parse().unwrap()]
            } else {
                vec![]
            }
        };
        let rs = render(&p, &p.pods["db"], &book).unwrap().unwrap();
        assert!(rs.contains("udp sport 67 udp dport 68 accept"), "{rs}");
        assert!(
            rs.contains(
                "ip saddr 192.0.2.10/32 tcp dport 5432 accept comment \"expose of service pg\""
            ),
            "{rs}"
        );
    }

    #[test]
    fn deny_rule_with_unknown_peer_fails_closed() {
        let yaml = BASE.replace(
            "        - { to: 198.51.100.0/24, action: reject }",
            "        - { to: 198.51.100.0/24, action: reject }\n        - { to: pod:db, action: drop }",
        );
        let p = project(&yaml);
        let book = |_: &str| -> Vec<IpNet> { vec![] };
        let err = render(&p, &p.pods["web"], &book).unwrap_err().to_string();
        assert!(err.contains("pod:db has no address yet"), "{err}");
    }

    #[test]
    fn unknown_peer_addresses_are_skipped() {
        let p = project(BASE);
        let book = |_: &str| -> Vec<IpNet> { vec![] };
        let rs = render(&p, &p.pods["web"], &book).unwrap().unwrap();
        // The db pod's address is unknown, so only the IPv6 peer remains.
        assert!(!rs.contains("192.0.2.50"));
        assert!(rs.contains("ip6 saddr 2001:db8::/32 tcp dport 9000 accept"));
    }
}
