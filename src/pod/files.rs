//! The /etc files every container in a pod shares: hosts, resolv.conf
//! and hostname. They live in the pod directory and are bind mounted.

use std::fmt::Write;
use std::net::IpAddr;
use std::path::Path;

pub fn resolv_conf(dns: &[IpAddr], search: &[String], options: &[String]) -> String {
    let mut s = String::from("# Generated by gantry\n");
    for d in dns {
        let _ = writeln!(s, "nameserver {d}");
    }
    if !search.is_empty() {
        let _ = writeln!(s, "search {}", search.join(" "));
    }
    if !options.is_empty() {
        let _ = writeln!(s, "options {}", options.join(" "));
    }
    s
}

/// Nameservers for a pod that sets none: the host's upstream servers.
/// Loopback resolvers (systemd-resolved's 127.0.0.53, dnsmasq on
/// 127.0.0.1) are unreachable from the pod and are skipped.
pub fn host_nameservers() -> (Vec<IpAddr>, Vec<String>) {
    let candidates = ["/run/systemd/resolve/resolv.conf", "/etc/resolv.conf"];
    for c in candidates {
        let Ok(text) = std::fs::read_to_string(c) else {
            continue;
        };
        let (dns, search) = parse_resolv(&text);
        let dns: Vec<IpAddr> = dns.into_iter().filter(|d| !d.is_loopback()).collect();
        if !dns.is_empty() {
            return (dns, search);
        }
    }
    (vec![], vec![])
}

pub fn parse_resolv(text: &str) -> (Vec<IpAddr>, Vec<String>) {
    let mut dns = Vec::new();
    let mut search = Vec::new();
    for line in text.lines() {
        let mut words = line.split_whitespace();
        match words.next() {
            Some("nameserver") => {
                if let Some(Ok(ip)) = words
                    .next()
                    .map(|w| w.split('%').next().unwrap_or(w).parse::<IpAddr>())
                {
                    dns.push(ip);
                }
            }
            Some("search") | Some("domain") => search = words.map(str::to_string).collect(),
            _ => {}
        }
    }
    (dns, search)
}

/// One line of the shared hosts file.
pub struct HostEntry {
    pub addr: IpAddr,
    pub names: Vec<String>,
}

pub fn hosts_file(entries: &[HostEntry]) -> String {
    let mut s = String::from(
        "# Generated by gantry\n127.0.0.1\tlocalhost\n::1\tlocalhost ip6-localhost ip6-loopback\n",
    );
    for e in entries {
        let mut names: Vec<&str> = Vec::new();
        for n in &e.names {
            if !names.contains(&n.as_str()) {
                names.push(n);
            }
        }
        if !names.is_empty() {
            let _ = writeln!(s, "{}\t{}", e.addr, names.join(" "));
        }
    }
    s
}

pub fn write_if_changed(path: &Path, content: &str) -> crate::Result<()> {
    clear_engine_mountpoint(path)?;
    if std::fs::read_to_string(path).ok().as_deref() == Some(content) {
        return Ok(());
    }
    crate::util::write_in_place(path, content.as_bytes())
}

/// After a reboot Docker restarts containers with a restart policy before
/// Gantry rebuilds their pod. It creates each missing bind source as an
/// empty directory, so the pod's hosts, hostname and resolv.conf can show
/// up as directories. Those paths are Gantry's own; an empty directory
/// there is removed. Anything else is left alone and reported.
fn clear_engine_mountpoint(path: &Path) -> crate::Result<()> {
    use crate::errors::Context;
    match std::fs::symlink_metadata(path) {
        Ok(md) if md.is_dir() => std::fs::remove_dir(path).ctx(|| {
            format!(
                "{} is a directory where Gantry writes a file, and it is not empty",
                path.display()
            )
        }),
        _ => Ok(()),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn replaces_an_empty_directory_left_by_an_engine() {
        let d = tempfile::tempdir().unwrap();
        let p = d.path().join("resolv.conf");
        std::fs::create_dir(&p).unwrap();
        write_if_changed(&p, "nameserver 1.1.1.1\n").unwrap();
        assert_eq!(std::fs::read_to_string(&p).unwrap(), "nameserver 1.1.1.1\n");
        let q = d.path().join("hosts");
        std::fs::create_dir(&q).unwrap();
        std::fs::write(q.join("keep"), "x").unwrap();
        assert!(write_if_changed(&q, "x").is_err());
        assert!(q.join("keep").exists());
    }

    #[test]
    fn resolv_roundtrip() {
        let text = resolv_conf(
            &["1.1.1.1".parse().unwrap()],
            &["example.com".into()],
            &["ndots:2".into()],
        );
        assert!(text.contains("nameserver 1.1.1.1\nsearch example.com\noptions ndots:2"));
        let (dns, search) = parse_resolv(&text);
        assert_eq!(dns.len(), 1);
        assert_eq!(search, vec!["example.com"]);
        let (dns, _) = parse_resolv("nameserver fe80::1%eth0\nnameserver 127.0.0.53\n");
        assert_eq!(dns.len(), 2);
    }

    #[test]
    fn hosts_dedupes_names() {
        let h = hosts_file(&[HostEntry {
            addr: "127.0.0.1".parse().unwrap(),
            names: vec!["web".into(), "web".into(), "app".into()],
        }]);
        assert!(h.contains("127.0.0.1\tweb app\n"), "{h}");
    }
}
